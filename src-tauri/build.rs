//! 构建脚本：保留 Tauri 的构建步骤，并把 `presets/<id>/` 每个目录压缩成字节，
//! 生成 `preset_bundles.rs`（注册为 `PRESETS`）。
//!
//! 预设以「普通 0.4 项目目录」形式可版本化维护（JSON + 资源），
//! 编译期由本脚本打包，避免手写二进制 ZIP 塞进 `&'static [u8]`。
//! 每个预设目录需包含 `preset.json`：`{ "id", "label", "description" }`。

use std::env;
use std::fs;
use std::io::Write;
use std::path::Path;
use zip::write::SimpleFileOptions;
use zip::CompressionMethod;

fn main() {
    tauri_build::build();

    bundle_presets();
}

fn bundle_presets() {
    println!("cargo:rerun-if-changed=presets");
    println!("cargo:rerun-if-changed=build.rs");

    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR");
    let presets_src = Path::new(&manifest_dir).join("presets");

    let mut gen = String::new();
    gen.push_str("// @generated by build.rs — 请勿手改。\n");
    gen.push_str("// 每个条目对应 presets/<id>/ 目录（0.4 项目快照）压缩而成。\n");
    gen.push_str("// 本文件被 include! 进 preset 模块，PresetDef 已在作用域内。\n");
    gen.push_str("pub static PRESETS: &[PresetDef] = &[\n");

    let mut entries: Vec<_> = if presets_src.exists() {
        fs::read_dir(&presets_src)
            .unwrap()
            .filter_map(|e| e.ok())
            .filter(|e| e.path().is_dir())
            .collect()
    } else {
        Vec::new()
    };
    entries.sort_by_key(|e| e.file_name().to_string_lossy().to_string());

    for entry in entries {
        let id = entry.file_name().to_string_lossy().to_string();
        let meta_path = entry.path().join("preset.json");
        let meta: serde_json::Value = if meta_path.exists() {
            serde_json::from_str(&fs::read_to_string(&meta_path).unwrap())
                .unwrap_or_else(|e| panic!("preset {id} 的 preset.json 不是合法 JSON: {e}"))
        } else {
            panic!("preset 目录 {id} 缺少 preset.json（需含 id / label / description）");
        };
        let label = meta["label"].as_str().unwrap_or("");
        let description = meta["description"].as_str().unwrap_or("");

        let zip_abs = Path::new(&out_dir).join(format!("presets/{id}.zip"));
        if let Some(parent) = zip_abs.parent() {
            fs::create_dir_all(parent).unwrap();
        }
        zip_dir(&entry.path(), &zip_abs);

        // include_bytes! 需要编译期绝对路径，统一成向前斜杠以兼容 Windows。
        let zip_lit = zip_abs.to_string_lossy().replace('\\', "/");
        gen.push_str(&format!(
            "    PresetDef {{ id: {id:?}, label: {label:?}, description: {description:?}, bytes: include_bytes!({zip_lit:?}) }},\n",
        ));
    }

    gen.push_str("];\n");

    let gen_path = Path::new(&out_dir).join("preset_bundles.rs");
    fs::write(&gen_path, gen).unwrap();
}

fn zip_dir(src: &Path, dest: &Path) {
    let file = fs::File::create(dest).unwrap_or_else(|e| panic!("创建 {dest:?} 失败: {e}"));
    let mut zip = zip::ZipWriter::new(file);
    let opts = SimpleFileOptions::default().compression_method(CompressionMethod::Deflated);
    add_dir(&mut zip, src, src, &opts);
    zip.finish().unwrap();
}

fn add_dir(
    zip: &mut zip::ZipWriter<std::fs::File>,
    root: &Path,
    dir: &Path,
    opts: &SimpleFileOptions,
) {
    for entry in fs::read_dir(dir).unwrap() {
        let entry = entry.unwrap();
        let path = entry.path();
        let rel = path.strip_prefix(root).unwrap().to_string_lossy().replace('\\', "/");
        if path.is_dir() {
            zip.add_directory(format!("{rel}/"), *opts).unwrap();
            add_dir(zip, root, &path, opts);
        } else {
            let data = fs::read(&path).unwrap();
            zip.start_file(rel, *opts).unwrap();
            zip.write_all(&data).unwrap();
        }
    }
}
